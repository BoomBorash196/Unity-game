using System;

[Serializable]
public class LevelConfig
{
    public float Thickness = 0.5f;
    public float MinSize = 1.9f;
    public float MaxSize = 3.2f;
    public float MinDy = 1.0f;
    public float MaxDy = 2.2f;
    public float MinDx = 2.8f;
    public float MaxDx = 3.8f;
    public float FallMargin = 15f;
    public int StreamAhead = 20;
    public int SupportBelow = 8;

    // --- размеры и форма платформ ---
    // Четыре формы вместо одного квадрата: ровный квадрат быстро надоедает,
    // а разница в размере и ориентации сама по себе делает трассу интереснее.
    public float SmallSize = 1.7f;        // маленькая — самая сложная для приземления
    public float WideSize = 5.0f;         // широкая — прощает промах, награждает за разбег
    public float LongLength = 4.6f;       // длинная узкая доска вдоль пути
    public float LongWidth = 1.6f;
    public float ShapeGap = 0.4f;         // минимальный просвет между соседними платформами

    // Веса форм. Сумма не обязана быть 100 — используются как вероятности.
    public int SquareWeight = 46;
    public int SmallWeight = 16;
    public int WideWeight = 24;
    public int LongWeight = 14;

    // --- опасности ---
    // Порог и разгон заданы высотой, а не номером платформы. Номер платформы
    // на разных ступенях несёт разный смысл: на Земле их 40, а на Раю под
    // сотым стоит уже тысячная. По высоте же ступени и устроены.
    //
    // Высота абсолютная, но конфиг берётся из текущей ступени, а высоты
    // площадок не убывают. Поэтому порог ниже начала ступени безопасен и
    // просто означает «с низа моей ступени». Ноль на верхних ступенях —
    // это «опасно сразу», а не «опасно с земли».
    //
    // Порог может стоять и чуть выше начала ступени: так первые метры
    // остаются спокойными, и на новой местности есть время осмотреться.
    public float HazardStartHeight = 34f;   // с этой высоты опасности начинаются

    /// <summary>Порог, отключающий опасности на ступени целиком.
    /// Число взято с запасом и не имеет физического смысла — настоящий
    /// подъём такой высоты просто не случится.</summary>
    public const float NoHazards = 9999f;
    public float HazardRampHeight = 220f;   // за сколько метров шанс доходит до максимума
    public float HazardChance = 0.16f;    // шанс на платформу в начале ступени
    public float HazardChanceMax = 0.30f; // и к её вершине
    /// <summary>Меньшая сторона площадки, с которой опасность ещё влезает.
    ///
    /// Задаётся на ступень, а не одно число на всю игру. Площадки к верху
    /// мельчают, и при одном общем пороге верхние ступени выпадали из отсева
    /// целиком: на Скалах ловушки ставились на 15 процентов площадок против 34
    /// у Карьера, то есть опасностей там было вчетверо меньше, чем на ступень
    /// ниже, которая задумывалась проще.
    ///
    /// Порог нельзя просто убрать: опасность всегда стоит в середине и занимает
    /// 42 процента меньшей стороны, так что по краям остаётся
    /// (minSide - 0.42 * minSide) / 2. При 2,4 метра это 0,70 м на сторону,
    /// при 1,8 — уже 0,52 м, и приземляться становится нечем. Поэтому спускаемся
    /// вместе с площадками, удерживая свободный край около 0,55 м.</summary>
    public float MinHazardPlatform = 2.4f;
}