using UnityEngine;

/// <summary>
/// Геометрия раскладки площадок. Вынесена из генератора не ради порядка в файле,
/// а ради проверяемости: правило «не наезжать» — это арифметика, в которой
/// легко перепутать местами множители, и ошибка в ней не падает. Уровень просто
/// тихо портится, а тест на «ноль наложений» без доступа к формуле ничего не
/// поймает. Здесь она живёт как чистые функции, которые считаются без запуска
/// Unity и без живой сцены.
///
/// Ось Y разбирается отдельно от XZ. Толщина у всех площадок одна, поэтому если
/// центры разошлись по высоте сильнее, чем сумма половин толщин с зазором,
/// площадки не соприкасаются ни при какой близости проекций. Такие пары
/// отбрасываются одним сравнением, и на них не тратится ни время, ни попытки
/// подбора места.
/// </summary>
public static class PlatformFit
{
    /// <summary>
    /// Радиус описанной окружности в горизонтальной плоскости.
    ///
    /// Считается по диагонали, а не по большей стороне. У длинной доски радиус
    /// заметно больше любой её стороны, и проверка по стороне пропускала бы две
    /// доски прямо друг сквозь друга углами — они пересекались бы, а тест
    /// говорил, что всё в порядке.
    /// </summary>
    public static float CircumRadius(Vector3 size)
    {
        return new Vector2(size.x, size.z).magnitude * 0.5f;
    }

    /// <summary>
    /// Минимальное расстояние между центрами, при котором две площадки не
    /// наезжают: сумма описанных радиусов плюс зазор.
    ///
    /// Формула обязана быть симметрична относительно обеих площадок. Вариант
    /// «половина суммы, плюс радиус соседа» выглядит похоже, но требовал
    /// radius*0.5 + other*1.5 вместо radius + other, и доска рядом с маленькой
    /// площадкой заезжала на неё почти на метр.
    /// </summary>
    public static float RequiredSeparation(float radiusA, float radiusB, float gap)
    {
        return radiusA + radiusB + gap;
    }

    /// <summary>
    /// Зазор между двумя площадками в метрах.
    ///
    /// Положительное число — не наезжают, и это же число и есть запас.
    /// Отрицательное — насколько глубоко одна залезла в другую.
    /// <see cref="float.PositiveInfinity"/> — площадки гарантированно не касаются.
    ///
    /// Возвращается именно величина, а не «проходит/не проходит»: при подборе
    /// места приходится выбирать из нескольких неудачных вариантов наименее
    /// плохой, и булева проверка для такого выбора не годится в принципе.
    /// </summary>
    public static float PairClearance(
        Vector3 centerA, float radiusA, float halfHeightA,
        Vector3 centerB, float radiusB, float halfHeightB,
        float gap)
    {
        // Разошлись по высоте сильнее, чем толщины вместе с зазором, — стоять
        // не поверх чего. На XZ смотреть бессмысленно: сближение проекций не
        // сделает площадки выше одна другой.
        if (Mathf.Abs(centerA.y - centerB.y) >= halfHeightA + halfHeightB + gap)
            return float.PositiveInfinity;

        float dx = centerA.x - centerB.x;
        float dz = centerA.z - centerB.z;
        return Mathf.Sqrt(dx * dx + dz * dz) - RequiredSeparation(radiusA, radiusB, gap);
    }

    /// <summary>
    /// Насколько далеко прыжок дотягивается, если набирает при этом высоту dy.
    /// Приземляться можно на нисходящей ветви: игрок взлетает, переваливается
    /// через apex и опускается на нужную площадку сверху.
    ///
    /// Дальность обязана зависеть от dy, а не быть одной константой на весь
    /// подъём. Прыжок, бьющий на 2,4 м вверх, долетает 5,54 м, а пологий —
    /// 7,39 м. Разница в полтора метра: взять дальность по пологому прыжку и
    /// посадить площадку после высокого шага — значит построить стену, на
    /// которую невозможно допрыгнуть.
    /// </summary>
    public static float ReachAt(float dy)
    {
        float v = PlayerPhysics.JumpSpeed;
        float g = PlayerPhysics.Gravity;
        float disc = v * v - 2f * g * dy;
        if (disc <= 0f) return 0f;
        float t = (v + Mathf.Sqrt(disc)) / g;
        return PlayerPhysics.RunSpeed * t;
    }

    /// <summary>
    /// Дальность прыжка с запасом на неточность. Использовать только её, а не
    /// <see cref="ReachAt"/> напрямую: последняя считает идеальный игрок,
    /// который в первый же кадр выходит на полную скорость и жмёт прыжок ровно
    /// в точку. Минус 6% — это и есть запас на реальность.
    /// </summary>
    public static float SafeReachAt(float dy)
    {
        return ReachAt(dy) * 0.94f;
    }
}